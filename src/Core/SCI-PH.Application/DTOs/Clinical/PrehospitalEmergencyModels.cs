using System.Text.Json.Serialization;
using SCI_PH.Application.Common.Serialization;
using SCI_PH.Domain.Enums.Encounters;
using SCI_PH.Domain.Enums.Medications;
using SCI_PH.Domain.Enums.Organizations;
using SCI_PH.Domain.Enums.Patients;
using SCI_PH.Domain.Enums.Transport;

namespace SCI_PH.Application.DTOs.Clinical
{
    // Opens a prehospital emergency for the authenticated paramedic (Mobile BFF). Everything else comes from the server:
    // no clinic (care before arriving at a hospital), NN patient, staff = the current user, NN code from the Domain.
    // Unknown members (location, clinicId, staffId, patientId, temporaryPatientCode...) are rejected with a 400.
    // clientRequestId: generated by the app once per emergency and kept across retries (idempotency key).
    // startedAt: when care started on the device, ISO-8601 with "Z" or an explicit offset (a value without offset is
    // rejected with a 400, see ExplicitOffsetInstantConverter) and read as UTC; accepted from 24 h in the past to 5 min
    // in the future.
    [JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]
    public sealed record OpenPrehospitalEmergencyRequest(
        [property: JsonRequired] Guid ClientRequestId,
        [property: JsonRequired, JsonConverter(typeof(ExplicitOffsetInstantConverter))] DateTimeOffset StartedAt,
        [property: JsonRequired] string ChiefComplaint);

    // Identifies the NN patient of an emergency by document (Mobile BFF). documentType: NationalId or Passport only (the
    // other types do not prove identity or are not entered by hand). documentNumber is sent as typed: the Domain normalizes
    // it and the match is exact in the SCI-PH platform scope (no issuer). clientRequestId: generated by the app once per
    // identification attempt and kept across retries; it is not the clientRequestId that opened the emergency.
    [JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]
    public sealed record IdentifyEmergencyByDocumentRequest(
        [property: JsonRequired] Guid ClientRequestId,
        [property: JsonRequired, JsonConverter(typeof(TextEnumConverter))] PatientIdentifierType DocumentType,
        [property: JsonRequired] string DocumentNumber);

    // One reading of vital signs taken by the paramedic (Mobile BFF): 1 to 7 values, all measured at recordedAt (ISO-8601
    // with "Z" or an explicit offset). Fixed fields, so a reading holds at most one value per type. No unit: the server
    // owns it (VitalSignLimits). Integers except temperature (at most 2 decimals). clientRequestId: generated by the app
    // once per reading and kept across retries; it is not the key of any other operation.
    [JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]
    public sealed record RecordEmergencyVitalSignsRequest(
        [property: JsonRequired] Guid ClientRequestId,
        [property: JsonRequired, JsonConverter(typeof(ExplicitOffsetInstantConverter))] DateTimeOffset RecordedAt,
        int? HeartRate = null,
        int? RespiratoryRate = null,
        int? SystolicPressure = null,
        int? DiastolicPressure = null,
        int? OxygenSaturation = null,
        decimal? Temperature = null,
        int? Glasgow = null);

    public sealed record EmergencyVitalSignMeasurement(
        [property: JsonConverter(typeof(TextEnumConverter))] VitalSignType Type,
        decimal Value,
        string Unit);

    // The recorded reading, built from the canonical request and the server-owned units, so a replay answers the same.
    public sealed record EmergencyVitalSignsSummary(
        Guid EncounterId,
        DateTimeOffset RecordedAtUtc,
        IReadOnlyList<EmergencyVitalSignMeasurement> Measurements);

    // Created = false: an idempotent replay of a reading this user already recorded with the same request.
    public sealed record RecordEmergencyVitalSignsResult(EmergencyVitalSignsSummary Reading, bool Created);

    // One entry of the fixed prehospital procedure catalog (PrehospitalProcedureCatalog): what the app shows and sends.
    public sealed record PrehospitalProcedureCatalogItem(string Code, string Name, string? Description);

    // A procedure the paramedic already performed (Mobile BFF). procedureCode: a code of the server's catalog; the name,
    // description and code system come from that catalog, never from the client. performedAt: ISO-8601 with "Z" or an
    // explicit offset, the single instant of a completed procedure. outcome: optional free text with the result.
    // Unknown members (name, description, codeSystem, staffId, completedAt, status...) are rejected with a 400.
    // clientRequestId: generated by the app once per procedure and kept across retries.
    [JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]
    public sealed record RecordEmergencyProcedureRequest(
        [property: JsonRequired] Guid ClientRequestId,
        [property: JsonRequired] string ProcedureCode,
        [property: JsonRequired, JsonConverter(typeof(ExplicitOffsetInstantConverter))] DateTimeOffset PerformedAt,
        string? Outcome = null);

    // The recorded procedure, built from the canonical request and the catalog entry, so a replay answers the same.
    public sealed record EmergencyProcedureSummary(
        Guid Id,
        Guid EncounterId,
        string Code,
        string Name,
        DateTimeOffset PerformedAtUtc,
        string? Outcome);

    // Created = false: an idempotent replay of a procedure this user already recorded with the same request.
    public sealed record RecordEmergencyProcedureResult(EmergencyProcedureSummary Procedure, bool Created);

    // One active entry of the global medication catalog, as the paramedic app shows it. No status: only active
    // medications are listed. Presentation and concentration tell apart entries with the same name.
    public sealed record PrehospitalMedicationCatalogItem(
        Guid Id,
        string? Code,
        string Name,
        string? Presentation,
        string? Concentration,
        [property: JsonConverter(typeof(TextEnumConverter))] MedicationRoute? DefaultRoute);

    // A dose the paramedic already gave (Mobile BFF). No prescription: the paramedic does not prescribe, so
    // prescriptionId and prescriptionDetailId are rejected like any unknown member (name, presentation, staffId...).
    // medicationId: an active medication of the catalog. dose: > 0, at most 3 decimals, below 1 000 000 000. doseUnit:
    // free text of 1 to 24 characters after trimming (the app's unit list is only a UI aid). route: a MedicationRoute name;
    // the medication's default route is a suggestion, not a rule. administeredAt: ISO-8601 with "Z" or an explicit offset.
    // notes: optional. clientRequestId: generated by the app once per dose and kept across retries.
    [JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]
    public sealed record RecordEmergencyMedicationAdministrationRequest(
        [property: JsonRequired] Guid ClientRequestId,
        [property: JsonRequired] Guid MedicationId,
        [property: JsonRequired] decimal Dose,
        [property: JsonRequired] string DoseUnit,
        [property: JsonRequired, JsonConverter(typeof(TextEnumConverter))] MedicationRoute Route,
        [property: JsonRequired, JsonConverter(typeof(ExplicitOffsetInstantConverter))] DateTimeOffset AdministeredAt,
        string? Notes = null);

    // The recorded dose, built from the canonical request and the medication's name, so a replay answers the same.
    public sealed record EmergencyMedicationAdministrationSummary(
        Guid Id,
        Guid EncounterId,
        Guid MedicationId,
        string MedicationName,
        decimal Dose,
        string DoseUnit,
        [property: JsonConverter(typeof(TextEnumConverter))] MedicationRoute Route,
        DateTimeOffset AdministeredAtUtc,
        string? Notes);

    // Created = false: an idempotent replay of a dose this user already recorded with the same request.
    public sealed record RecordEmergencyMedicationAdministrationResult(EmergencyMedicationAdministrationSummary Administration, bool Created);

    // An observation written by the paramedic (Mobile BFF). The type is always Prehospital (fixed by the server) and the
    // author is the session's staff. content: 1 to 8000 characters after trimming. occurredAt: ISO-8601 with "Z" or an
    // explicit offset. Unknown members (type, authorStaffId, patientId, createdAtUtc...) are rejected with a 400.
    // clientRequestId: generated by the app once per note and kept across retries.
    [JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]
    public sealed record RecordEmergencyNoteRequest(
        [property: JsonRequired] Guid ClientRequestId,
        [property: JsonRequired, JsonConverter(typeof(ExplicitOffsetInstantConverter))] DateTimeOffset OccurredAt,
        [property: JsonRequired] string Content);

    // The recorded note, built from the canonical request, so a replay answers the same. No author (always the caller)
    // and no creation time (not part of the request).
    public sealed record EmergencyNoteSummary(
        Guid Id,
        Guid EncounterId,
        [property: JsonConverter(typeof(TextEnumConverter))] ClinicalNoteType Type,
        string Content,
        DateTimeOffset OccurredAtUtc);

    // Created = false: an idempotent replay of a note this user already recorded with the same request.
    public sealed record RecordEmergencyNoteResult(EmergencyNoteSummary Note, bool Created);

    // Mobile read model of a prehospital emergency. Patient stays null until the NN patient is identified.
    // ActiveTransfer: the Requested or InTransit transfer of the emergency, so the app can restore its transfer screen; null
    // when there is none (added at the end: older clients ignore it).
    public sealed record PrehospitalEmergencySummary(
        Guid Id,
        string? TemporaryPatientCode,
        [property: JsonConverter(typeof(TextEnumConverter))] ClinicalEncounterStatus Status,
        DateTimeOffset StartedAtUtc,
        string? ChiefComplaint,
        PatientSummary? Patient,
        EmergencyTransferSummary? ActiveTransfer = null);

    // One emergency of the paramedic's active list (GET api/mobile/emergencies/active): only what the list shows and the
    // app needs to pick the case, never the full patient. PatientDisplayName is null while the patient is NN; the NN code
    // stays after identification as traceability. ActiveTransferStatus: Requested or InTransit, null without an active
    // transfer. To resume the case the app reads the emergency again (GET api/mobile/emergencies/{id}).
    public sealed record ActivePrehospitalEmergencySummary(
        Guid Id,
        string? TemporaryPatientCode,
        string? PatientDisplayName,
        [property: JsonConverter(typeof(TextEnumConverter))] ClinicalEncounterStatus Status,
        DateTimeOffset StartedAtUtc,
        string? ChiefComplaint,
        [property: JsonConverter(typeof(TextEnumConverter))] ClinicalTransferStatus? ActiveTransferStatus);

    // Read-store row of an emergency assigned to a staff member, with the status of its active transfer (if any).
    public sealed record AssignedEmergencyRow(EncounterRow Encounter, ClinicalTransferStatus? ActiveTransferStatus);

    // A clinic a paramedic can take the patient to: any active clinic of the network (no restriction by type).
    public sealed record TransferDestinationSummary(
        Guid Id,
        string Name,
        [property: JsonConverter(typeof(TextEnumConverter))] ClinicType Type,
        string Municipality,
        string Province);

    // Read model of a clinic as a transfer destination, with its status for the request's check.
    public sealed record TransferDestinationRow(Guid Id, string Name, ClinicType Type, string Municipality, string Province, ClinicStatus Status)
    {
        public TransferDestinationSummary ToSummary() => new(Id, Name, Type, Municipality, Province);
    }

    // Requests the transfer of the emergency to a clinic (Mobile BFF). Origin: none (care outside a clinic). The time and
    // the staff come from the server; originClinicId, requestedAtUtc, status, ambulanceId... are rejected with a 400.
    // reason: optional, at most 500 characters. notes: optional, at most 4000. clientRequestId: generated by the app once
    // per request and kept across retries.
    [JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]
    public sealed record RequestEmergencyTransferRequest(
        [property: JsonRequired] Guid ClientRequestId,
        [property: JsonRequired] Guid DestinationClinicId,
        string? Reason = null,
        string? Notes = null);

    // A transfer of a prehospital emergency as the paramedic app sees it.
    public sealed record EmergencyTransferSummary(
        Guid Id,
        Guid EncounterId,
        [property: JsonConverter(typeof(TextEnumConverter))] ClinicalTransferStatus Status,
        TransferDestinationSummary Destination,
        DateTimeOffset RequestedAtUtc,
        DateTimeOffset? SentAtUtc,
        DateTimeOffset? CancelledAtUtc);

    // Created = false: an idempotent replay of a request this user already made with the same clientRequestId.
    public sealed record RequestEmergencyTransferResult(EmergencyTransferSummary Transfer, bool Created);

    // Created = false: an idempotent replay of an emergency this user already opened with the same request.
    public sealed record OpenPrehospitalEmergencyResult(PrehospitalEmergencySummary Emergency, bool Created);
}
