using System.Text.Json.Serialization;
using SCI_PH.Application.Abstractions.Biometrics;
using SCI_PH.Application.Common.Serialization;

namespace SCI_PH.Application.DTOs.Biometrics
{
    // ---- Device API (the reader) ----

    // The capture job of a reader: only the session to answer and until when. Never a patient, an emergency, a reference
    // or an expected slot.
    public sealed record PendingFingerprintSession(Guid SessionId, DateTimeOffset ExpiresAtUtc);

    // What the sensor reported, matched on the sensor (SCI-PH never receives a template or an image).
    public enum FingerprintCaptureOutcome
    {
        Match = 1,
        NoMatch = 2,
        LowQuality = 3,
        SensorError = 4
    }

    // Result of a capture. slot: the sensor slot that matched, required for Match and rejected otherwise. The reader is
    // identified by its credential only: a deviceId or any other member is rejected with a 400.
    [JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]
    public sealed record SubmitFingerprintResultRequest(
        [property: JsonRequired, JsonConverter(typeof(TextEnumConverter))] FingerprintCaptureOutcome Outcome,
        int? Slot);

    // ---- Mobile BFF (the paramedic) ----

    // An active reader with the fingerprint scope. LastSeenAtUtc: its last authenticated contact, as recorded by the
    // Device API (not an online status).
    public sealed record FingerprintReaderSummary(Guid Id, string Code, string Name, DateTimeOffset? LastSeenAtUtc);

    // Opens a fingerprint session on the emergency with the reader the paramedic chose. clientRequestId: generated by the
    // app once per session and kept across retries.
    [JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]
    public sealed record OpenFingerprintSessionRequest(
        [property: JsonRequired] Guid ClientRequestId,
        [property: JsonRequired] Guid DeviceId);

    // Confirms the candidate of a Matched session. No patient id: the server takes it from the session's reference.
    [JsonUnmappedMemberHandling(JsonUnmappedMemberHandling.Disallow)]
    public sealed record ConfirmFingerprintSessionRequest([property: JsonRequired] Guid ClientRequestId);

    // Enough for the paramedic to confirm visually: no patient id, no identifier, no biometric reference.
    public sealed record FingerprintCandidate(string DisplayName, DateOnly? DateOfBirth);

    // failure: LowQuality or SensorError when Failed. candidate: only while Matched and its reference is still active.
    public sealed record FingerprintSessionSummary(
        Guid Id,
        [property: JsonConverter(typeof(TextEnumConverter))] FingerprintSessionStatus Status,
        Guid ReaderId,
        DateTimeOffset ExpiresAtUtc,
        [property: JsonConverter(typeof(TextEnumConverter))] FingerprintCaptureOutcome? Failure,
        FingerprintCandidate? Candidate);

    public sealed record OpenFingerprintSessionResult(FingerprintSessionSummary Session, bool Created);
}
